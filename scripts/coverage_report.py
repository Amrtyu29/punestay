"""Writes data/COVERAGE.md: what the PG / hostel / flat data covers and what is still missing.

Uses the same queries as GET /admin/coverage (backend/app/services/coverage.py).

Usage:
    python scripts/coverage_report.py
"""
import sys
from datetime import date
from pathlib import Path

from psycopg.rows import dict_row

from common import DATA, ROOT, connect

sys.path.insert(0, str(ROOT))
from backend.app.services.coverage import coverage  # noqa: E402


def pct(n, d):
    return f"{round(100 * n / d)}%" if d else "—"


def main():
    with connect() as conn, conn.cursor(row_factory=dict_row) as cur:
        c = coverage(cur)
    k = c["completeness"]
    total = k["listings"]
    L = [f"# Data coverage report ({date.today().isoformat()})", "",
         "Generated by `scripts/coverage_report.py`. The same numbers are live on the Admin page.", "",
         "## Listings", "", "| Measure | Count | Share |", "|---|---|---|",
         f"| Listings | {total} | |"]
    for key, label in [("with_phone", "Have a phone number"), ("with_website", "Have a website"),
                       ("rent_confirmed", "Rent published (owner or two students)"), ("verified", "Verified by 3 people"),
                       ("gender_known", "Boys / girls known"), ("amenities_known", "Amenities known"),
                       ("with_photos", "Have photos"), ("in_two_sources", "Confirmed by two open datasets")]:
        L.append(f"| {label} | {k[key]} | {pct(k[key], total)} |")
    L += ["", "### By source and type", "", "| Source | Type | Listings |", "|---|---|---|"]
    L += [f"| {r['source']} | {r['listing_type']} | {r['n']} |" for r in c["by_source_type"]]

    L += ["", "## Where listings are thin", "",
          "Localities with at least 5 colleges or offices within 2 km but 3 or fewer listings. "
          "Demand score = 3 × colleges + offices.", "",
          "| Locality | Colleges | Offices | Listings | Past flat rents | Demand score |", "|---|---|---|---|---|---|"]
    L += [f"| {r['locality']} | {r['colleges']} | {r['offices']} | {r['listings']} | {r['past_flat_rents']} | {r['demand_score']} |"
          for r in c["thin_localities"]]

    no = c["colleges_without_listings_1500m"]
    L += ["", f"## Colleges with no listing within 1.5 km ({len(no)} of {c['colleges_total']})", ""]
    L += [f"- {x['name']}" for x in no[:60]]
    if len(no) > 60:
        L.append(f"- … and {len(no) - 60} more")

    ro = c["rent_observations"]
    L += ["", "## Past flat rents", "",
          f"{sum(ro.values())} real 2021 flat rents loaded; {ro.get('building', 0)} placed on a named building, "
          f"{ro.get('locality', 0)} known only to the locality.", ""]
    (DATA / "COVERAGE.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {DATA / 'COVERAGE.md'}: {total} listings, {len(c['thin_localities'])} thin localities, "
          f"{len(no)} colleges without nearby listings")


if __name__ == "__main__":
    main()
